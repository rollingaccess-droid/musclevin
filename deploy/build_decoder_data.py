#!/usr/bin/env python3
"""Regenerate deploy/assets/decoder-data.js from the Python decoder tables.

The Python module is the source of truth. Run this after editing tables in
app/decoder.py, then run the parity tests.
"""
from __future__ import annotations

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "app"))
import decoder as d  # noqa: E402

OUT = pathlib.Path(__file__).resolve().parent / "assets" / "decoder-data.js"


def _rows(mapping):
    return {k: [list(row) for row in rows] for k, rows in mapping.items()}


def tables():
    """JSON-ready tables. Sets become sorted lists; int keys become strings."""
    return {
        "GM_DIVISION": d.GM_DIVISION,
        "CHEV_SERIES_6571": {k: list(v) for k, v in d.CHEV_SERIES_6571.items()},
        "CHEV_SERIES_7280": d.CHEV_SERIES_7280,
        "GM_BODY": d.GM_BODY,
        "CHEV_PLANTS": d.CHEV_PLANTS,
        "PONT_SERIES_6571": d.PONT_SERIES_6571,
        "PONT_PLANTS": d.PONT_PLANTS,
        "CHEV_ENGINE_1972": d.CHEV_ENGINE_1972,
        "CHEV_ENGINE_7380": d.CHEV_ENGINE_7380,
        "FORD_PLANTS": d.FORD_PLANTS,
        "FORD_BODY": _rows(d.FORD_BODY),
        "FORD_ENGINE": _rows(d.FORD_ENGINE),
        "MOPAR_LINE": d.MOPAR_LINE,
        "MOPAR_CLASS": d.MOPAR_CLASS,
        "MOPAR_MODELNAME": d.MOPAR_MODELNAME,
        "MOPAR_BODY": d.MOPAR_BODY,
        "MOPAR_ENGINE": {str(year): codes for year, codes in d.MOPAR_ENGINE.items()},
        "MOPAR_PLANTS": d.MOPAR_PLANTS,
        "MOPAR_PLANTS_6667": d.MOPAR_PLANTS_6667,
        "MOPAR_FENDER_ENGINE": d.MOPAR_FENDER_ENGINE,
        "MOPAR_E_TO_VIN": {
            code: [[a, z, sorted(chars)] for a, z, chars in windows]
            for code, windows in d.MOPAR_E_TO_VIN.items()
        },
    }


def render():
    payload = json.dumps(tables(), indent=2, ensure_ascii=False)
    return (
        "// Generated by deploy/build_decoder_data.py from app/decoder.py.\n"
        "// Do not edit by hand. The Python tables are the source of truth.\n"
        "export const TABLES = "
        + payload
        + ";\n"
    )


def main():
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("decoder-data.js is out of date. Run: python3 deploy/build_decoder_data.py", file=sys.stderr)
            return 1
        print("decoder-data.js matches app/decoder.py")
        return 0
    if "--stdout" in sys.argv:
        sys.stdout.write(json.dumps(tables()))
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
